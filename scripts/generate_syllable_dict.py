#!/usr/bin/env python3
"""Generate a sparse dictionary with the main dictionary's exact syllable IDs."""

import argparse
import re
from pathlib import Path


def collect_syllables(path: Path, syllables: set[str]) -> None:
    """Read this project's text/code dictionaries and their imported tables."""
    with path.open(encoding="utf-8-sig") as input_file:
        header_lines = []
        for line in input_file:
            if line.strip() == "...":
                break
            header_lines.append(line)
        for line in input_file:
            if not line.strip() or line.startswith("#"):
                continue
            syllables.update(line.split("\t")[1].split())

    imports = re.search(
        r"^import_tables:\n((?:[ \t]+.*\n|\n)*)", "".join(header_lines), re.MULTILINE
    )
    if imports:
        for name in re.findall(r"^\s+-\s+([^\s#]+)", imports[1], re.MULTILINE):
            collect_syllables(path.parent / (name + ".dict.yaml"), syllables)


def generate(directory: Path, dictionary: str, version: str) -> None:
    syllables: set[str] = set()
    collect_syllables(directory / (dictionary + ".dict.yaml"), syllables)
    code = " ".join(sorted(syllables, key=lambda value: value.encode("utf-8")))
    (directory / "wanxiang_syllables.dict.yaml").write_text(
        "# Rime dictionary\n"
        "# encoding: utf-8\n"
        "# Generated by scripts/generate_syllable_dict.py. DO NOT EDIT.\n"
        "# A sentinel phrase retains the main dictionary's syllable IDs.\n"
        "---\n"
        "name: wanxiang_syllables\n"
        f'version: "{version}"\n'
        "sort: original\n"
        "use_preset_vocabulary: false\n"
        "...\n"
        f"placeholder\t{code}\t0\n",
        encoding="utf-8",
    )
    print(f"{directory}: {len(syllables)} syllables")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="packaged schema directory")
    parser.add_argument("--dictionary", default="wanxiang", help="main dictionary name")
    parser.add_argument("--tag", help="upstream release tag")
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    if args.tag is not None:
        version = args.tag.removeprefix("v")
    else:
        with (args.directory / "wanxiang_syllables.dict.yaml").open(
            encoding="utf-8-sig"
        ) as input_file:
            version = next(
                line.partition(":")[2].strip().strip('"')
                for line in input_file
                if line.startswith("version:")
            )

    generate(args.directory, args.dictionary, version)


if __name__ == "__main__":
    raise SystemExit(main())
