"""Generate the English dictionary from ESDB words and wordfreq weights.

Words come from the English Speller Database (ESDB, formerly SCOWL), a curated
speller word list whose size levels rank words by commonness. Weights come from
wordfreq, a word frequency estimate over multiple corpora.

Usage::

    uv run scripts/generate_english_dict.py --esdb <esdb_dir> [--repo-root <dir>]
"""

import argparse
import re
import sqlite3
import subprocess
import unicodedata
from importlib.metadata import version as package_version
from pathlib import Path

from wordfreq import tokenize, word_frequency

DICT_PATH = Path("dicts/english.dict.yaml")
DICT_NAME = "english"

ESDB_URL = "https://github.com/en-wl/wordlist"
ESDB_DB_FILE = "scowl.db"
ESDB_COPYRIGHT_FILE = "Copyright"
ESDB_MAX_SIZE = 60
ESDB_WORD_QUERY = f"""
SELECT DISTINCT word FROM scowl_v0
WHERE size <= {ESDB_MAX_SIZE}
    AND variant_level <= 1
    AND spelling IN ('_', 'A', 'B', 'Z')
    AND region IN ('', 'US', 'GB')
    AND pos not IN ('np', 'nsp', 'nssp', 'wep', 'weps')
    AND pos_category <> 'nonword'
    AND category IN ('', 'hacker')
    AND usage_note NOT LIKE 'offensive%'
"""

WORDFREQ_URL = "https://pypi.org/project/wordfreq"
WORDFREQ_LANGUAGE = "en"

SINGLE_WORD_PATTERN = re.compile(r"[^\W\d_]+(?:'[^\W\d_]+)?")
SINGLE_LETTER_WORDS = {"a", "I"}


def select_words(esdb_db_path: Path) -> list[str]:
    """Return ESDB words that pass the selection rules."""
    with sqlite3.connect(f"{esdb_db_path.as_uri()}?mode=ro", uri=True) as connection:
        esdb_words = [word for (word,) in connection.execute(ESDB_WORD_QUERY)]

    return [
        word
        for word in esdb_words
        if SINGLE_WORD_PATTERN.fullmatch(word)
        and len(tokenize(word, WORDFREQ_LANGUAGE)) == 1
        and (len(word) > 1 or word in SINGLE_LETTER_WORDS)
    ]


def weigh_words(words: list[str]) -> dict[str, int]:
    """Map each word to its wordfreq frequency per billion words."""
    return {
        word: round(word_frequency(word, WORDFREQ_LANGUAGE) * 1e9) for word in words
    }


def remove_diacritics(word: str) -> str:
    """Return the word with combining marks removed, such as café to cafe."""
    decomposed = unicodedata.normalize("NFD", word)
    return "".join(char for char in decomposed if not unicodedata.combining(char))


def format_entry(word: str, weight: int) -> str:
    """Return one dictionary entry line, omitting the weight column when it is 0."""
    code = remove_diacritics(word)
    if weight == 0:
        return f"{word}\t{code}\n"
    return f"{word}\t{code}\t{weight}\n"


def read_esdb_commit(esdb_dir: Path) -> tuple[str, str]:
    """Return the ESDB checkout's commit hash and commit date."""
    output = subprocess.run(
        ["git", "-C", str(esdb_dir), "log", "-1", "--format=%H %cs"],
        check=True,
        stdout=subprocess.PIPE,
        text=True,
    ).stdout
    commit, date = output.split()
    return commit, date


def read_esdb_notice(esdb_dir: Path) -> tuple[str, str]:
    """Return the ESDB copyright line and permission notice."""
    copyright_text = (esdb_dir / ESDB_COPYRIGHT_FILE).read_text(encoding="utf-8")
    copyright_line, permission_notice = copyright_text.split("\n\n")[:2]
    return copyright_line, permission_notice


def build_dict_text(weights: dict[str, int], esdb_dir: Path) -> str:
    """Return the dictionary file text with attribution header and entries."""
    esdb_commit, esdb_date = read_esdb_commit(esdb_dir)
    esdb_copyright, esdb_permission_notice = read_esdb_notice(esdb_dir)
    wordfreq_version = package_version("wordfreq")

    header_lines = [
        "Rime dictionary",
        "encoding: utf-8",
        "",
        "Generated by scripts/generate_english_dict.py, licensed under CC BY-SA 4.0.",
        "",
        "Words source: English Speller Database (ESDB)",
        f"Original repository: {ESDB_URL}/tree/{esdb_commit}",
        f"{esdb_copyright}, licensed under the following notice:",
        "",
        *esdb_permission_notice.splitlines(),
        "",
        "Weights source: wordfreq by Robyn Speer",
        f"Original package: {WORDFREQ_URL}/{wordfreq_version}/",
        "Data licensed under CC BY-SA 4.0.",
        "wordfreq includes data from Google Books Ngrams, Google Books Syntactic",
        "Ngrams, the Leeds Internet Corpus, Wikipedia, ParaCrawl, OPUS OpenSubtitles",
        "2018, the freely available SUBTLEX word lists by Marc Brysbaert et al., and",
        "the streaming Twitter API.",
    ]
    header = "".join(f"# {line}".rstrip() + "\n" for line in header_lines)

    directive_lines = [
        "---",
        f"name: {DICT_NAME}",
        f'version: "{esdb_date}"',
        "sort: by_weight",
        "...",
    ]
    directives = "".join(f"{line}\n" for line in directive_lines)

    entries = "".join(
        format_entry(word, weights[word])
        for word in sorted(weights, key=lambda word: (word.lower(), word))
    )

    return header + directives + entries


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--esdb",
        required=True,
        type=Path,
        help=f"Path to an ESDB checkout with {ESDB_DB_FILE} built by 'make'.",
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="Repository root to write into (default: this script's parent directory).",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    esdb_dir = args.esdb.resolve()

    words = select_words(esdb_dir / ESDB_DB_FILE)
    weights = weigh_words(words)
    dict_text = build_dict_text(weights, esdb_dir)

    output_path = args.repo_root.resolve() / DICT_PATH
    output_path.write_text(dict_text, encoding="utf-8")
    print(f"==> Wrote {len(weights)} entries to {DICT_PATH.as_posix()}")


if __name__ == "__main__":
    main()
